// Общие шаги сценариев с заявками. Файлы с `_` раннер тестами не считает.
//
// Когда выносить шаг сюда: он повторяется в нескольких тестах И называет бизнес-действие
// («открыть заявку», «заполнить новую заявку») — тогда тест читается как сценарий, а детали
// навигации живут в одном месте. Одиночный вызов API в хелпер не оборачиваем: `clickElement
// ('Утвердить')` в тесте понятнее любой обёртки. Первый аргумент хелпера — участник сценария
// (контекст роли), так один хелпер служит любой роли.

// Заявки эталона. У каждой свой комментарий — по нему их и находим: после других тестов
// заявок в том же статусе станет больше, а комментарий эталонной не меняется.
export const заявкаЭталона = {
  черновик: { 'Комментарий': 'Канцелярия' },
  наСогласовании: { 'Комментарий': 'Обучение сотрудников' },
  утверждённая: { 'Комментарий': 'Командировка' },
};

export async function открытьСписокЗаявок(пользователь) {
  await пользователь.navigateSection('Заявки');
  return пользователь.openCommand('Заявки на расход');
}

export async function открытьЗаявку(пользователь, какую) {
  await открытьСписокЗаявок(пользователь);
  await пользователь.clickElement({ row: какую, column: 'Номер' }, { dblclick: true });
  return пользователь.getFormState();
}

// Создать и заполнить новую заявку, не записывая: форма остаётся открытой
export async function заполнитьНовуюЗаявку(пользователь, реквизиты) {
  await открытьСписокЗаявок(пользователь);
  await пользователь.clickElement('Создать');
  await пользователь.fillFields(реквизиты);
  return пользователь.getFormState();
}

export const статусЗаявки = (форма) => форма.texts?.find((надпись) => надпись.name === 'Статус')?.value;
export const номерЗаявки = (форма) => форма.fields?.find((поле) => поле.name === 'Номер')?.value;

// Команда пользователю недоступна: скрыта (не положена роли) или выключена (не тот статус)
export function командаНедоступна(форма, команда) {
  const кнопка = форма.buttons?.find((b) => b.name === команда);
  return !кнопка || Boolean(кнопка.disabled);
}

// Чем решение объяснило отказ — сообщения пользователю; null, если действие прошло
export async function причинаОтказа(пользователь, действие) {
  try {
    await действие();
    return null;
  } catch {
    return ((await пользователь.getFormState()).errors?.messages || []).join('\n');
  }
}
