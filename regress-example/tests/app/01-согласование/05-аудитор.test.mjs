import { открытьСписокЗаявок, открытьЗаявку, заявкаЭталона, командаНедоступна } from './_заявки.mjs';

// Что проверяем: роль только для чтения — аудитор видит заявки, но ни записать, ни отправить,
// ни согласовать не может.
//
// Приём — проверка прав и альтернативный вход. Контекст auditor в webtest.config.mjs указывает на
// публикацию без пользователя и задаёт пользователя у контекста (`user: 'Аудитор'`): так входят,
// когда состав пользователей меняется и публиковать под каждого неудобно. Для теста разницы нет.
// «Недоступна» = команды нет на форме (роли не положена) или она выключена — пользователю
// одинаково недоступна, поэтому проверяем одним `командаНедоступна`.
//
// Как сделать так же: для каждой ограниченной роли — тест «видит / не меняет»: открывается ли
// нужное, недоступны ли изменяющие команды. Список команд — явный, не «все кнопки формы».

export const name = 'Аудитор видит заявки, но не меняет их';
export const tags = ['согласование', 'права', 'req-005'];
export const context = 'auditor';

export default async function({ step, assert, ...аудитор }) {
  await step('Аудитор видит список заявок', async () => {
    await открытьСписокЗаявок(аудитор);
    assert.tableHasRow(await аудитор.readTable(), заявкаЭталона.утверждённая);
  });

  await step('Заявка открывается только для просмотра', async () => {
    const заявка = await открытьЗаявку(аудитор, заявкаЭталона.наСогласовании);
    for (const команда of ['Записать', 'Отправить на согласование', 'Утвердить', 'Отклонить']) {
      assert.ok(командаНедоступна(заявка, команда), `«${команда}» аудитору недоступна`);
    }
  });

  await аудитор.closeForm();
}
