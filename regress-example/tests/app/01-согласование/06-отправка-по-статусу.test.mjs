import { открытьЗаявку, заявкаЭталона, командаНедоступна } from './_заявки.mjs';

// Что проверяем: отправить на согласование можно только черновик.
//
// Приём — табличный сценарий по данным эталона. В отличие от 04, документы не создаются: строка
// таблицы указывает на готовую заявку эталона (`какая` — отбор по комментарию из заявкаЭталона)
// и ожидание для неё. Тест ничего не записывает, поэтому порядок прогона ему не важен.
// В строке можно держать любые значения, в том числе объекты — в имя попадают только ключи из
// шаблона ({заявка}, {ожидание}).
//
// Как сделать так же: для правил «от состояния зависит доступность» — заранее положить в эталон
// по документу на каждое состояние и пройти их таблицей.
export const name = 'Отправка на согласование, заявка {заявка}: {ожидание}';
export const tags = ['согласование', 'req-001'];
export const context = 'init';
export const params = [
  { заявка: 'черновик',        какая: заявкаЭталона.черновик,       ожидание: 'можно',  можноОтправить: true },
  { заявка: 'на согласовании', какая: заявкаЭталона.наСогласовании, ожидание: 'нельзя', можноОтправить: false },
  { заявка: 'утверждённая',    какая: заявкаЭталона.утверждённая,   ожидание: 'нельзя', можноОтправить: false },
];

export default async function({ step, assert, ...инициатор }, { какая, можноОтправить }) {
  await step('Открыть заявку и посмотреть на команду отправки', async () => {
    const заявка = await открытьЗаявку(инициатор, какая);
    assert.equal(!командаНедоступна(заявка, 'Отправить на согласование'), можноОтправить);
  });

  await инициатор.closeForm({ save: false });
}
