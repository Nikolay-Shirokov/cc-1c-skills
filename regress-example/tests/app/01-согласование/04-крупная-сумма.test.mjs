import { заполнитьНовуюЗаявку, причинаОтказа } from './_заявки.mjs';

// Что проверяем: правило расширения «заявка свыше 100 000 требует комментария» — на границе и
// по обе стороны от неё.
//
// Приём — табличный сценарий (`export const params`). Раннер ещё до запуска разворачивает
// каждую строку таблицы в отдельный тест: свой статус в отчёте, свой скриншот при падении,
// чистый рабочий стол на старте; одна упавшая строка не мешает остальным. В имя теста
// подставляются значения строки по ключу ({случай}). При выполнении строка приходит вторым
// аргументом функции — разбираем её на переменные обычной деструктуризацией JS.
// Граница — 100 000: ровно столько ещё можно без комментария, на копейку больше — уже нельзя.
//
// Как сделать так же: правило с порогом или вариантами — таблица «вход → ожидание»; строка на
// каждую границу и типичный случай; ожидание храните в строке (здесь `записывается`), а не в
// условиях по значениям. Новый случай — новая строка, код теста не меняется.
export const name = 'Крупная заявка: {случай}';
export const tags = ['согласование', 'расширение', 'req-004'];
export const context = 'init';
export const params = [
  { случай: '99 999,99 без комментария записывается',   сумма: '99999,99',  комментарий: '',                     записывается: true },
  { случай: '100 000 без комментария записывается',     сумма: '100000',    комментарий: '',                     записывается: true },
  { случай: '100 000,01 без комментария отклоняется',   сумма: '100000,01', комментарий: '',                     записывается: false },
  { случай: '150 000 с комментарием записывается',      сумма: '150000',    комментарий: 'Закупка оборудования', записывается: true },
];

export default async function({ step, assert, ...инициатор }, { сумма, комментарий, записывается }) {
  await step(`Заполнить заявку на ${сумма}`, async () => {
    await заполнитьНовуюЗаявку(инициатор, {
      'Подразделение': 'Бухгалтерия',
      'Сумма': сумма,
      ...(комментарий && { 'Комментарий': комментарий }),
    });
  });

  await step(записывается ? 'Заявка записывается' : 'Запись отклоняется: нужен комментарий', async () => {
    const причина = await причинаОтказа(инициатор, () => инициатор.clickElement('Записать'));
    if (записывается) assert.equal(причина, null, 'проверка заполнения пропускает заявку');
    else assert.match(причина ?? 'записалась', /свыше 100 000 укажите комментарий/);
  });

  await инициатор.closeForm({ save: false });
}
