import { заполнитьНовуюЗаявку, открытьЗаявку, открытьСписокЗаявок, статусЗаявки, номерЗаявки } from './_заявки.mjs';

// Что проверяем: процесс целиком — инициатор отправляет, согласующий утверждает, инициатор
// видит результат.
//
// Приём — процесс из нескольких ролей в одном тесте. `export const contexts = ['init', 'appr']`
// открывает два сеанса 1С; в первом аргументе они приходят под своими id — переименовываем по
// ролям при разборе аргумента. Вызов через участника (`согласующий.clickElement`) сам переключает
// активный сеанс. Связь между шагами — номер заявки: его читаем после записи и по нему находим
// заявку у другой роли, а не «первую в списке».
// Сеансы держат лицензии 1С: лишние раннер закрывает сам по maxContexts в webtest.config.mjs.
// Список у инициатора открыт до утверждения и не знает об изменении — переоткрываем его.
//
// Как сделать так же: перечислить роли процесса в contexts, передавать между шагами
// идентификатор документа, проверять итог глазами той роли, которой он важен.

export const name = 'Согласующий утверждает отправленную заявку';
export const tags = ['согласование', 'req-002'];
export const severity = 'critical';
export const contexts = ['init', 'appr'];

export default async function({ init: инициатор, appr: согласующий, step, assert }) {
  let номер;

  await step('Инициатор отправляет заявку', async () => {
    await заполнитьНовуюЗаявку(инициатор, { 'Подразделение': 'Бухгалтерия', 'Сумма': '30000', 'Комментарий': 'Семинар' });
    await инициатор.clickElement('Отправить на согласование');
    номер = номерЗаявки(await инициатор.getFormState());
    assert.ok(номер, 'у отправленной заявки есть номер');
    await инициатор.closeForm();
  });

  await step('Согласующий её утверждает', async () => {
    await открытьЗаявку(согласующий, { 'Номер': номер });
    await согласующий.clickElement('Утвердить');
    assert.equal(статусЗаявки(await согласующий.getFormState()), 'Утверждена');
    await согласующий.closeForm();
  });

  await step('Инициатор видит заявку утверждённой', async () => {
    await инициатор.closeForm(); // список открыт до утверждения — переоткрываем
    await открытьСписокЗаявок(инициатор);
    assert.tableHasRow(await инициатор.readTable(), { 'Номер': номер, 'Статус': 'Утверждена' });
  });
}
