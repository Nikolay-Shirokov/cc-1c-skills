import { заполнитьНовуюЗаявку, статусЗаявки, номерЗаявки, командаНедоступна } from './_заявки.mjs';

// Что проверяем: инициатор создаёт заявку и отправляет её на согласование; после отправки
// заявка записана, статус «На согласовании», повторно отправить или утвердить её он не может.
//
// Приём — сценарий под одной ролью. `export const context = 'init'` выбирает контекст из
// webtest.config.mjs (публикация под пользователем «Инициатор»). В первом аргументе приходят
// и инструменты теста (step, assert), и действия пользователя: инструменты разбираем в
// сигнатуре, действия собираем под именем роли — тест читается как текст (инициатор.clickElement).
// Шаги (`step`) — по-русски, утвердительно: они попадают в консоль и в отчёт Allure.
// Документ создаём свой, а не правим общий из эталона, — тест не зависит от порядка прогона.
//
// Как сделать так же: роль → контекст; шаги — бизнес-действия; утверждения — о том, что видит
// пользователь (статус, номер, доступность команд), а не о внутренностях формы.

export const name = 'Инициатор отправляет заявку на согласование';
export const tags = ['согласование', 'req-001'];
export const context = 'init';

export default async function({ step, assert, ...инициатор }) {
  await step('Новая заявка — черновик', async () => {
    const заявка = await заполнитьНовуюЗаявку(инициатор,
      { 'Подразделение': 'Отдел продаж', 'Сумма': '12000', 'Комментарий': 'Канцтовары' });
    assert.equal(статусЗаявки(заявка), 'Черновик');
  });

  await step('Отправленная заявка — на согласовании', async () => {
    await инициатор.clickElement('Отправить на согласование');
    const заявка = await инициатор.getFormState();
    assert.equal(статусЗаявки(заявка), 'На согласовании');
    assert.ok(номерЗаявки(заявка), 'заявка записана — у неё есть номер');
    assert.ok(командаНедоступна(заявка, 'Отправить на согласование'), 'повторно отправить нельзя');
    assert.ok(командаНедоступна(заявка, 'Утвердить'), 'утверждать инициатор не может');
  });

  await инициатор.closeForm();
}
