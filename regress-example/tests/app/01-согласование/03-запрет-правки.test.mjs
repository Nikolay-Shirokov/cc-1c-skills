import { открытьЗаявку, заявкаЭталона, причинаОтказа } from './_заявки.mjs';

// Что проверяем: утверждённую заявку изменить нельзя — запись отклоняется, и пользователь
// видит понятную причину.
//
// Приём — проверка отказа. Действие, которое платформа отклонила, бросает исключение с текстом
// её окна («Не удалось записать…») — это не причина. Причину решение сообщает пользователю,
// она лежит в getFormState().errors.messages; её и проверяем (`причинаОтказа`).
// Данные — из эталона: утверждённую заявку находим по её комментарию, а не по статусу — после
// других тестов утверждённых станет больше. Форму закрываем без записи.
//
// Как сделать так же: действие, которое должно быть отклонено, — в `причинаОтказа`; проверять
// текст сообщения регулярным выражением по смыслу, а не дословно целиком.

export const name = 'Запись утверждённой заявки отклоняется с объяснением';
export const tags = ['согласование', 'req-003'];
export const context = 'init';

export default async function({ step, assert, ...инициатор }) {
  await step('Инициатор пытается записать утверждённую заявку', async () => {
    await открытьЗаявку(инициатор, заявкаЭталона.утверждённая);
    const причина = await причинаОтказа(инициатор, () => инициатор.clickElement('Записать'));
    assert.match(причина ?? 'записалась', /Утверждённую заявку изменять нельзя/);
  });

  await инициатор.closeForm({ save: false });
}
